-- VALDY STORE: rating dan komentar produk tanpa login
-- Jalankan sekali di Supabase Dashboard > SQL Editor > New query.

create table if not exists public.product_reviews (
  id bigint generated by default as identity primary key,
  product_id text not null check (product_id ~ '^product-[0-9]{3}$'),
  reviewer_name text not null
    check (char_length(trim(reviewer_name)) between 1 and 60),
  rating integer not null check (rating between 1 and 5),
  comment text not null check (char_length(trim(comment)) between 2 and 1000),
  created_at timestamptz not null default now()
);

create index if not exists product_reviews_product_created_idx
  on public.product_reviews (product_id, created_at desc);

alter table public.product_reviews enable row level security;

drop policy if exists "Public can read product reviews" on public.product_reviews;
create policy "Public can read product reviews"
  on public.product_reviews for select
  to anon, authenticated
  using (true);

drop policy if exists "Visitors can submit product reviews" on public.product_reviews;
create policy "Visitors can submit product reviews"
  on public.product_reviews for insert
  to anon, authenticated
  with check (
    product_id ~ '^product-[0-9]{3}$'
    and rating between 1 and 5
    and char_length(trim(comment)) between 2 and 1000
    and char_length(trim(reviewer_name)) between 1 and 60
  );

grant select, insert on public.product_reviews to anon, authenticated;
grant usage, select on sequence public.product_reviews_id_seq to anon, authenticated;

-- Aktifkan pembaruan ulasan secara langsung (Realtime) jika belum terdaftar.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime'
         and schemaname = 'public'
         and tablename = 'product_reviews'
     ) then
    alter publication supabase_realtime add table public.product_reviews;
  end if;
end $$;
